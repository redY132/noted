async page => {
  // Playwright CLI function. Use an isolated browser session or disposable NOTED_WORKSPACE.
  await page.setViewportSize({width:1200,height:900});
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const settle = () => page.evaluate(() => Promise.all(document.getAnimations().filter(a => a.effect?.getTiming().iterations !== Infinity).map(a => a.finished.catch(() => {}))));
  const visible = async selector => { await settle(); return page.locator(selector).isVisible(); };
  const panel = async (name, open) => {
    if (!await visible('#view-popover')) await page.locator('#view-toggle').click();
    await page.locator(`[data-panel-choice="${name}"]`).setChecked(open);
    await page.keyboard.press('Escape');
  };
  await page.locator('#view-toggle').click();
  await page.locator('#reset-layout').click();
  await page.keyboard.press('Escape');
  await page.locator('#appearance-toggle').click();
  await page.locator('#reset-appearance').click();
  await page.keyboard.press('Escape');
  assert(await visible('#notes-panel'), 'Default note list missing');
  for (const id of ['navigation-panel','formatting-tools','layout-tools','note-details','note-footer','connections-panel']) assert(!await visible('#'+id), 'Default panel visible: '+id);
  assert(await page.locator('.shell-topbar').evaluate(el => el.getBoundingClientRect().height) === 36, 'Top bar is not 36px');
  await page.locator('#view-toggle').click();
  const previous = await page.locator('#header-connection-handle button').count() ? await page.locator('#header-connection-handle button').getAttribute('data-connect-source') : null;
  await page.locator('#shell-new-note').click();
  await page.waitForFunction(old => !document.querySelector('#note-pane').inert && document.querySelector('#header-connection-handle button')?.dataset.connectSource !== old, previous);
  await page.locator('#note-title').fill('Minimal shell verification');
  const content = page.getByRole('textbox', {name:'Note content',exact:true});
  await content.fill('Words and formatting stay intact.');
  await content.press('Control+a');
  await page.evaluate(() => { window.__shellEditor = document.querySelector('#editor .tiptap'); });
  await page.locator('[data-panel-toggle="formatting"]').click();
  await page.getByRole('button',{name:'Bold',exact:true}).click();
  assert(await content.locator('strong').innerText() === 'Words and formatting stay intact.', 'Opening formatting lost selection');
  await page.getByRole('combobox',{name:'Text color',exact:true}).selectOption('#275c98');
  await page.locator('[data-panel-toggle="formatting"]').click();
  await content.press('Control+f');
  assert(await visible('#find-panel') && !await visible('#formatting-tools'), 'Find expanded formatting or stayed hidden');
  await page.locator('#find-query').fill('formatting');
  await page.locator('#find-close').click();
  await panel('components',true);
  await content.press('Control+a');
  await page.getByRole('button',{name:'Text panel',exact:false}).click();
  await page.getByRole('combobox',{name:'Component placement',exact:true}).selectOption('free');
  for (const [name,value] of [['Component X','1200'],['Component Y','1500']]) {
    const field = page.getByRole('spinbutton',{name,exact:true});
    await field.fill(value); await field.press('Tab');
  }
  const position = await page.locator('.note-panel').evaluate(el => ({x:el.dataset.x,y:el.dataset.y,left:el.style.left,top:el.style.top}));
  for (const name of ['navigation','notes','details','footer','connections']) await panel(name,true);
  await page.locator('#appearance-toggle').click();
  await page.keyboard.press('F8');
  assert(!await visible('#appearance-popover'), 'Focus mode left popover open');
  for (const id of ['navigation-panel','notes-panel','formatting-tools','layout-tools','note-details','note-footer','connections-panel']) assert(!await visible('#'+id), 'Focus mode left panel open: '+id);
  assert(await page.locator('.workspace').evaluate(el => Math.round(el.getBoundingClientRect().width)) === (await page.viewportSize()).width, 'Editor did not reclaim viewport');
  await page.keyboard.press('F8');
  for (const id of ['navigation-panel','notes-panel','layout-tools','note-details','note-footer','connections-panel']) assert(await visible('#'+id), 'Focus mode did not restore: '+id);
  assert(await page.evaluate(() => window.__shellEditor === document.querySelector('#editor .tiptap')), 'Editor recreated');
  assert(JSON.stringify(position) === JSON.stringify(await page.locator('.note-panel').evaluate(el => ({x:el.dataset.x,y:el.dataset.y,left:el.style.left,top:el.style.top}))), 'Free coordinates changed');
  assert((await content.innerText()).includes('Words and formatting stay intact.'), 'Words changed');
  assert(await content.locator('strong').count() > 0 && await content.locator('[style*="color"]').count() > 0, 'Explicit formatting changed');
  const scrollable = await page.locator('.document-scroll').evaluate(el => { el.scrollTop=1800; el.scrollLeft=1300; return el.scrollTop > 0 && el.scrollLeft > 0; });
  assert(scrollable,'Free content cannot be reached by scrolling');
  await content.press('Control+z');
  assert(await page.locator('.note-panel').evaluate(el=>el.style.top) === '0px','Panel toggles altered undo history');
  await content.press('Control+Shift+z');
  assert(await page.locator('.note-panel').evaluate(el=>el.style.top) === '1500px','Redo history lost');
  await page.locator('#appearance-toggle').click();
  await page.locator('#appearance-mode').selectOption('dark');
  await page.locator('#appearance-accent').fill('#f9db35');
  assert(await page.locator('html').getAttribute('data-theme') === 'dark','Dark theme missing');
  await page.keyboard.press('Escape');
  await page.keyboard.press('Control+s');
  await page.waitForFunction(() => document.querySelector('#save-state').textContent.includes('Saved'));
  await page.reload();
  await page.waitForFunction(() => document.querySelector('#editor .tiptap'));
  assert(await page.locator('html').getAttribute('data-theme') === 'dark','Theme did not persist');
  assert(await page.locator('html').evaluate(el => el.style.getPropertyValue('--accent')) === '#f9db35','Accent did not persist');
  assert(await visible('#navigation-panel') && await visible('#connections-panel') && !await visible('#formatting-tools'),'Layout did not persist');
  assert((await content.innerText()).includes('Words and formatting stay intact.'),'Reload lost words');
  await page.locator('#appearance-toggle').click();
  await page.locator('#appearance-mode').selectOption('system');
  await page.emulateMedia({colorScheme:'light'});
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'light');
  assert(await page.locator('html').getAttribute('data-theme') === 'light','System light not followed');
  await page.emulateMedia({colorScheme:'dark'});
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'dark');
  await page.locator('#reset-appearance').click();
  assert(await page.locator('#appearance-mode').inputValue() === 'system' && await page.locator('#appearance-accent').inputValue() === '#52525b','Appearance reset failed');
  await page.keyboard.press('Escape');
  await panel('notes',false);
  await page.locator('#view-toggle').focus();
  await page.keyboard.press('/');
  assert(await visible('#notes-panel') && await page.locator('#search').evaluate(el=>el===document.activeElement),'Workspace search did not recover list');
  await page.locator('#view-toggle').click();
  await page.locator('#reset-layout').click();
  await page.keyboard.press('Escape');
  await page.locator('#appearance-toggle').click();
  await page.locator('#appearance-mode').selectOption('light');
  await page.keyboard.press('Escape');
  await page.locator('.document-scroll').evaluate(el=>{el.scrollTop=0;el.scrollLeft=0;});
  for (const width of [800,1200,1600]) {
    await page.setViewportSize({width,height:900});
    for(const mode of ['light','dark']) {
      await page.locator('#appearance-toggle').click();
      await page.locator('#appearance-mode').selectOption(mode);
      await page.keyboard.press('Escape');
      await panel('connections',true);
      if(width>=1440) assert(await page.locator('#connections-panel').evaluate(el=>getComputedStyle(el).position)!=='fixed','Wide panel did not dock');
      else assert(await page.locator('#connections-panel').evaluate(el=>getComputedStyle(el).position)==='fixed','Narrow panel did not overlay');
      await settle();
      await page.screenshot({path:`output/playwright/shell-${width}-${mode}.png`});
      await panel('connections',false);
    }
  }
  await page.emulateMedia({reducedMotion:'reduce'});
  assert(await page.locator('#app').evaluate(el=>getComputedStyle(el).transitionDuration) === '0s','Reduced motion still animates layout');
  await page.locator('[data-panel-toggle="navigation"]').click();
  assert(await visible('#navigation-panel'),'Reduced-motion panel unavailable');
  await page.emulateMedia({reducedMotion:'no-preference'});
  assert(await page.locator('#app').evaluate(el=>getComputedStyle(el).transitionDuration) !== '0s','Fluid layout transition missing');
  return {passed:true,selection:true,formatting:true,editorIdentity:true,freeCoordinates:true,scrolling:true,focusRestoration:true,persistence:true,systemTheme:true,breakpoints:[800,1200,1600]};
}
